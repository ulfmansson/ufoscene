#!/usr/bin/env zsh
# Build the UFO site and deploy it to Cloudflare (Workers static assets).
#
#   cd site && ./deploy-cloudflare.sh                       # workers.dev only
#   cd site && ./deploy-cloudflare.sh ufoscene.net           # + custom domain
#   cd site && ./deploy-cloudflare.sh ufoscene.net --dry-run # check, upload nothing
#
# A custom domain must be a zone in the same Cloudflare account (bought at Cloudflare, or
# its nameservers pointed there). Cloudflare then creates the DNS record and the certificate.
# Needs `npx wrangler login` once. Extra arguments go to `wrangler deploy`.
set -euo pipefail
SITE="${0:A:h}"
cd "$SITE"

DOMAIN=""
if [[ $# -gt 0 && "$1" != -* ]]; then
  DOMAIN="${1:l}"
  shift
  if [[ ! "$DOMAIN" =~ '^([a-z0-9]([a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,}$' ]]; then
    print -u2 "deploy-cloudflare.sh: '$DOMAIN' does not look like a domain name (example: ufoscene.net)"
    exit 1
  fi
fi

./build.sh

# wrangler.jsonc plus the route for the domain, as plain JSON (comments stripped).
python3 - "$DOMAIN" <<'EOF'
import json, re, sys
domain = sys.argv[1]
text = open('wrangler.jsonc', encoding='utf-8').read()
text = re.sub(r'^\s*//.*$', '', text, flags=re.M)  # whole-line comments only
config = json.loads(text)
if domain:
    config['routes'] = [{'pattern': domain, 'custom_domain': True}]
with open('wrangler.deploy.jsonc', 'w', encoding='utf-8') as f:
    f.write('// generated by deploy-cloudflare.sh from wrangler.jsonc; edit that file instead\n')
    json.dump(config, f, indent=2, ensure_ascii=False)
    f.write('\n')
EOF

npx --yes wrangler@4 deploy --config wrangler.deploy.jsonc "$@"

if [[ -n "$DOMAIN" && " $* " != *" --dry-run "* ]]; then
  print "\nSpotify: add https://$DOMAIN/callback under Redirect URIs at https://developer.spotify.com/dashboard"
fi
